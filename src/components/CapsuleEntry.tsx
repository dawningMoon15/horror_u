import React, { useState } from 'react';
import { decodeCapsule, DECODE_ERROR_MESSAGES } from '../game/decodeCapsule';
import { mapPersonalisation } from '../game/mapPersonalisation';
import { generateSampleCapsule } from '../game/promptGenerator';
import type { GameConfig } from '../game/schema';
import { sound } from '../lib/soundEffects';

interface CapsuleEntryProps {
  sessionToken: string;
  initialPaste?: string;
  onSuccess: (config: GameConfig) => void;
  onStartGeneric: () => void;
  onBack: () => void;
}

const MAX_BYTES = 8192;

export const CapsuleEntry: React.FC<CapsuleEntryProps> = ({
  sessionToken,
  initialPaste = '',
  onSuccess,
  onStartGeneric,
  onBack,
}) => {
  const [pasteValue, setPasteValue] = useState(initialPaste);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const [isProcessing, setIsProcessing] = useState(false);

  const byteLength = new TextEncoder().encode(pasteValue).length;
  const isTooLarge = byteLength > MAX_BYTES;

  const handleInputChange = (e: React.ChangeEvent<HTMLTextAreaElement>) => {
    setPasteValue(e.target.value);
    if (errorMessage) setErrorMessage(null);
  };

  const handleClear = () => {
    sound.playKeyClick();
    setPasteValue('');
    setErrorMessage(null);
  };

  const handleFillSample = () => {
    sound.playKeyClick();
    const sample = generateSampleCapsule(sessionToken, 'retro_computers');
    setPasteValue(sample);
    setErrorMessage(null);
  };

  const handleSubmit = (e?: React.FormEvent) => {
    if (e) e.preventDefault();
    if (!pasteValue.trim() || isTooLarge) return;

    sound.playKeyClick();
    setIsProcessing(true);
    setErrorMessage(null);

    // Run local decoding and mapping
    const decodeResult = decodeCapsule(pasteValue);
    if (!decodeResult.ok) {
      sound.playErrorBuzz();
      setIsProcessing(false);
      setErrorMessage(DECODE_ERROR_MESSAGES[decodeResult.reason]);
      return;
    }

    const mapResult = mapPersonalisation(decodeResult.capsule, sessionToken);
    if (!mapResult.ok) {
      sound.playErrorBuzz();
      setIsProcessing(false);
      setErrorMessage(
        'Session mismatch: This capsule was created for a different session token. Please generate a fresh capsule using the prompt above.',
      );
      return;
    }

    // Success! Immediately purge the raw paste from ephemeral component state
    sound.playSuccessChime();
    sound.stopAllAudio();
    setPasteValue('');
    setIsProcessing(false);
    onSuccess(mapResult.config);
  };

  const handleGeneric = () => {
    sound.playKeyClick();
    sound.stopAllAudio();
    onStartGeneric();
  };

  const handleBack = () => {
    sound.playKeyClick();
    onBack();
  };

  return (
    <main className="capsule-entry-screen" role="main">
      <div className="badge-tag green">
        <span aria-hidden="true">🔒</span> STEP 2: TRUST BOUNDARY INGESTION
      </div>

      <h1 className="screen-title">PASTE MEMORY CAPSULE</h1>
      <p className="screen-subtitle">
        Paste the base64 capsule string generated by your assistant. The payload will be decoded and
        validated locally against allowlists. The raw string is discarded immediately upon entry.
      </p>

      {/* Error Banner */}
      {errorMessage && (
        <div
          className="callout-box danger"
          id="capsule-error-banner"
          role="alert"
          style={{ marginBottom: '1.25rem' }}
        >
          <span>⚠</span>
          <div>
            <strong>Ingestion Blocked:</strong> {errorMessage}
          </div>
        </div>
      )}

      {/* Ephemeral Paste Form */}
      <form onSubmit={handleSubmit} className="terminal-panel" aria-label="Capsule Paste Form">
        <div className="panel-titlebar">
          <span>EPHEMERAL_BUFFER // MAXIMUM SIZE 8,192 BYTES</span>
          <div style={{ display: 'flex', gap: '0.5rem', alignItems: 'center' }}>
            <span
              style={{
                fontSize: '0.75rem',
                color: isTooLarge ? 'var(--color-crimson-alert)' : 'var(--color-text-muted)',
              }}
            >
              {byteLength.toLocaleString()} / {MAX_BYTES.toLocaleString()} bytes
            </span>
            <button
              type="button"
              id="btn-fill-sample"
              className="icon-btn-toggle"
              onClick={handleFillSample}
              title="Populate a valid sample capsule for this session"
            >
              ⚡ Fill Sample
            </button>
            {pasteValue && (
              <button
                type="button"
                id="btn-clear-capsule"
                className="icon-btn-toggle"
                onClick={handleClear}
                title="Clear input"
              >
                ✕ Clear
              </button>
            )}
          </div>
        </div>

        <div className="panel-body">
          <label htmlFor="capsule-textarea" className="form-label">
            Base64 Encoded Payload:
          </label>
          <textarea
            id="capsule-textarea"
            className="terminal-textarea"
            rows={7}
            placeholder="eyJ2ZXJzaW9uIjoiMSIsInNlc3Npb24iOiI..."
            value={pasteValue}
            onChange={handleInputChange}
            disabled={isProcessing}
            spellCheck={false}
            autoComplete="off"
            aria-invalid={!!errorMessage}
            aria-describedby={errorMessage ? 'capsule-error-banner' : undefined}
          />

          <div
            style={{
              display: 'flex',
              justifyContent: 'space-between',
              alignItems: 'center',
              marginTop: '1rem',
              flexWrap: 'wrap',
              gap: '0.75rem',
            }}
          >
            <div style={{ fontSize: '0.78rem', color: 'var(--color-text-muted)' }}>
              🔒 Content is processed in client RAM and wiped upon successful mapping.
            </div>

            <button
              type="submit"
              id="btn-submit-capsule"
              className="btn btn-primary"
              disabled={!pasteValue.trim() || isTooLarge || isProcessing}
            >
              {isProcessing ? 'PROCESSING...' : 'INITIALIZE ARCHIVE (ENTER ROOM) →'}
            </button>
          </div>
        </div>
      </form>

      {/* Navigation Options */}
      <div className="btn-group">
        <button
          type="button"
          id="btn-capsule-back"
          className="btn btn-secondary"
          onClick={handleBack}
        >
          <span>←</span> BACK TO PROMPT
        </button>

        <button
          type="button"
          id="btn-capsule-generic"
          className="btn btn-ghost"
          onClick={handleGeneric}
        >
          <span>◈</span> SWITCH TO GENERIC MODE (NO CAPSULE)
        </button>
      </div>
    </main>
  );
};
